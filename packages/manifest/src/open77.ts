// What a SCRIPT//GO resource becomes on OPEN//77, and the file set of a protected (escrow) release.
//
// One place for both, because two builders must agree byte for byte: `scriptgo pack`/`publish` on a
// creator's machine and the master when it protects an uploaded archive. OPEN//77's server refuses an
// escrowed resource unless its `open77.lua` is a SIGNED clear file of the release and every script
// that manifest lists belongs to the signed release. So the generated OPEN//77 files are part of the
// bundle, as clear files, and never produced unsigned at install time.
import { readFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { expandGlob } from "./files.ts";
import { scriptLanguage, type ParsedManifest } from "./manifest.ts";

// The shim is three files so the shared part references no server-only native: OPEN//77's
// validator flags those in a shared_script, and its client sandbox lacks `os` and `setmetatable`.
export const OPEN77_SHIM = [
  { from: "shim.lua", to: "scriptgo_shim.lua", directive: "shared_script" },
  { from: "shim_server.lua", to: "scriptgo_shim_server.lua", directive: "server_script" },
  { from: "shim_client.lua", to: "scriptgo_shim_client.lua", directive: "client_script" },
] as const;

/** The files generated for OPEN//77 next to a SCRIPT//GO resource: its manifest and the shim. */
export const OPEN77_GENERATED_FILES: readonly string[] = ["open77.lua", ...OPEN77_SHIM.map((s) => s.to)];

/** sdk/adapters/open77 in this repository (a published CLI bundles `sdk/`). */
export const OPEN77_SHIM_DIR = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..", "..", "sdk", "adapters", "open77");

/**
 * Keeps a shim's `-- @capability <name>` ... `-- @end` sections only for the capabilities the
 * manifest asks for, so the packed resource neither references nor needs permissions for natives
 * it never uses (OPEN//77's validator checks permissions against every native a file names).
 */
export function stripCapabilitySections(text: string, caps: Set<string>): string {
  const out: string[] = [];
  let keep = true;
  let open: string | null = null;
  for (const line of text.split(/\r?\n/)) {
    const start = /^--\s*@capability\s+([a-z_]+)\s*$/.exec(line);
    if (start) {
      if (open) throw new Error(`shim: @capability ${start[1]} opened inside @capability ${open}`);
      open = start[1]!;
      keep = caps.has(open);
      continue;
    }
    if (/^--\s*@end\s*$/.test(line)) {
      if (!open) throw new Error("shim: @end without @capability");
      open = null;
      keep = true;
      continue;
    }
    if (keep) out.push(line);
  }
  if (open) throw new Error(`shim: @capability ${open} is never closed`);
  return out.join("\n");
}

const quote = (s: string): string => JSON.stringify(s);
const list = (items: string[]): string => `{ ${items.map(quote).join(", ")} }`;

/**
 * Turns a SCRIPT//GO range into OPEN//77 dependency constraints (comparators against 1-3 part
 * numbers). `^` and `~` become two comparators; `||` cannot be expressed and is dropped.
 */
export function toOpen77Constraint(range: string | null): { constraint: string | null; warning?: string } {
  if (!range || range === "*") return { constraint: null };
  if (range.includes("||")) return { constraint: null, warning: `range '${range}' uses ||, which OPEN//77 cannot express; dropped` };
  const out: string[] = [];
  for (const token of range.replace(/(>=|<=|>|<|=|\^|~)\s+/g, "$1").split(/\s+/).filter(Boolean)) {
    const m = /^(>=|<=|>|<|==?|\^|~)?v?(\d+)(?:\.(\d+|x|\*))?(?:\.(\d+|x|\*))?$/.exec(token);
    if (!m) return { constraint: null, warning: `range '${range}' is not expressible in OPEN//77; dropped` };
    const [, op = "", maj, min, pat] = m;
    const n = (v: string | undefined): number | null => (v === undefined || v === "x" || v === "*" ? null : Number(v));
    const M = Number(maj), mi = n(min), p = n(pat);
    const ver = [M, mi ?? 0, p ?? 0].join(".");
    if (op === "^") {
      const upper = M > 0 || mi === null ? `${M + 1}.0.0` : mi > 0 || p === null ? `0.${mi + 1}.0` : `0.0.${(p ?? 0) + 1}`;
      out.push(`>=${ver}`, `<${upper}`);
    } else if (op === "~") {
      out.push(`>=${ver}`, `<${mi === null ? `${M + 1}.0.0` : `${M}.${mi + 1}.0`}`);
    } else {
      out.push(`${op === "==" ? "=" : op || "="}${ver}`);
    }
  }
  return { constraint: out.join(" ") };
}

export function open77Manifest(m: ParsedManifest, warnings: string[], source = "scriptgo.lua"): string {
  const lines: string[] = [
    `-- Generated by \`scriptgo pack --target open77\` from ${source} ${m.version}. Edit ${source}, not this file.`,
    `resource ${quote(m.name)}`,
    `version ${quote(m.version)}`,
    `open77_version ${quote(m.open77Version ?? "*")}`,
    `auto_start ${m.autoStart ? "true" : "false"}`,
  ];
  const permissions = new Set(m.permissions);
  const caps = new Set([...m.capabilities, ...m.optionalCapabilities]);
  // The shim reads the server ACL for ScriptGo.permissions and sends notifications over the network.
  if (caps.has("permissions")) permissions.add("acl.read");
  if (caps.has("ui")) permissions.add("network.events");
  // ScriptGo.http and ScriptGo.licensing go through Open77.http.request (server side).
  if (caps.has("http") || caps.has("licensing")) permissions.add("http.request");
  if (permissions.size > 0) lines.push(`permissions ${list([...permissions].sort())}`);
  for (const dep of m.dependencies) {
    const { constraint, warning } = toOpen77Constraint(dep.range);
    if (warning) warnings.push(`dependency ${dep.name}: ${warning}`);
    lines.push(`dependency ${quote(constraint ? `${dep.name} ${constraint}` : dep.name)}`);
  }
  // OPEN//77 loads scripts in manifest order, so the shim comes before every script of the resource.
  lines.push("");
  for (const s of OPEN77_SHIM) lines.push(`${s.directive} ${quote(s.to)}`);
  for (const p of m.sharedScripts) lines.push(`shared_script ${quote(p)}`);
  for (const p of m.environmentScripts["open77"] ?? []) lines.push(`shared_script ${quote(p)}`);
  for (const p of m.serverScripts) lines.push(`server_script ${quote(p)}`);
  for (const p of m.clientScripts) lines.push(`client_script ${quote(p)}`);
  if (m.files.length > 0) lines.push(`files ${list(m.files)}`);
  if (m.webFiles.length > 0) lines.push(`web_files ${list(m.webFiles)}`);
  if (m.exports.length > 0) lines.push(`exports ${list(m.exports)}`);
  if (m.serverExports.length > 0) lines.push(`server_exports ${list(m.serverExports)}`);
  if (m.webUiPage) warnings.push("web_ui_page has no OPEN//77 equivalent; use web_files and WebUI.Page");
  for (const env of Object.keys(m.environmentScripts)) {
    if (env !== "open77") warnings.push(`environment_script "${env}" is not shipped to OPEN//77`);
  }
  if (!m.environments.includes("open77") && m.environments.length > 0) {
    warnings.push("the manifest does not list open77 in environments; the package is untested there");
  }
  if (caps.has("http") || caps.has("licensing")) {
    warnings.push(
      "outbound HTTP is off on an OPEN//77 server until the operator sets server.jsonc http.enabled and lists every host the resource calls in http.allowedHosts" +
        (caps.has("licensing") ? " (licensing calls the SCRIPT//GO API at the scriptgo_api convar, default http://localhost:4100)" : ""),
    );
  }
  return lines.join("\n") + "\n";
}

/** The three shim files, cut to the capabilities the manifest asks for: exactly what `pack --target open77` writes. */
export function open77ShimFiles(m: ParsedManifest, shimDir: string = OPEN77_SHIM_DIR): Map<string, Buffer> {
  const caps = new Set<string>([...m.capabilities, ...m.optionalCapabilities]);
  const out = new Map<string, Buffer>();
  for (const s of OPEN77_SHIM) out.set(s.to, Buffer.from(stripCapabilitySections(readFileSync(join(shimDir, s.from), "utf8"), caps), "utf8"));
  return out;
}

/** The scripts an OPEN//77 server or client would load from this resource. */
function open77Scripts(m: ParsedManifest): string[] {
  return [...m.sharedScripts, ...m.serverScripts, ...m.clientScripts, ...(m.environmentScripts["open77"] ?? [])];
}

/**
 * Whether a SCRIPT//GO package can run on OPEN//77 once packed for it: written in the SCRIPT//GO
 * format, every script it ships is Lua, and its `environments` is empty or lists open77. A resource
 * already in OPEN//77 format needs nothing generated: its own open77.lua is its manifest.
 */
export function open77Capable(m: ParsedManifest): boolean {
  if (m.format !== "scriptgo") return false;
  if (m.environments.length > 0 && !m.environments.includes("open77")) return false;
  return open77Scripts(m).every((p) => scriptLanguage(p) === "lua");
}

/** Paths a host sends to game clients: they cannot be secret, so they must be clear in a bundle. */
export function clientFacingFiles(m: ParsedManifest, all: string[]): string[] {
  const out = new Set<string>();
  const add = (pattern: string): void => {
    for (const f of expandGlob(pattern, all)) out.add(f);
  };
  for (const p of [...m.sharedScripts, ...m.clientScripts, ...m.files, ...m.webFiles]) add(p);
  // OPEN//77 loads its environment scripts as shared scripts, so they reach clients too.
  for (const p of m.environmentScripts["open77"] ?? []) add(p);
  if (m.webUiPage) add(m.webUiPage);
  return [...out].sort();
}

export class EscrowFileSetError extends Error {
  constructor(
    readonly code: string,
    message: string,
  ) {
    super(message);
  }
}

export interface EscrowFileSet {
  /** The resource's files plus, for an OPEN//77-capable package, the generated OPEN//77 files. */
  files: Map<string, Buffer>;
  /** Clear-text patterns for the bundle: client-facing files, generated files, then the creator's. */
  allowlist: string[];
  /** The OPEN//77 files added (empty when the package cannot run there or is already in its format). */
  generated: string[];
  warnings: string[];
}

/**
 * The file set of a protected release, the same whoever builds the bundle:
 *  - files a host sends to game clients stay clear (shared and client scripts, files, web files, the
 *    web UI page, OPEN//77 environment scripts): only server-side code is encrypted;
 *  - a package that can run on OPEN//77 carries, as clear files covered by the release signature,
 *    the generated `open77.lua` and the three shim files, exactly as `pack --target open77` writes
 *    them. A name clash with a file of the resource is refused, never silently overwritten.
 */
export function prepareEscrowFiles(opts: {
  manifest: ParsedManifest;
  manifestFile: string;
  files: Map<string, Buffer>;
  /** Extra clear-text globs the creator names (config, schemas). */
  allowlist: string[];
  shimDir?: string;
}): EscrowFileSet {
  const m = opts.manifest;
  const files = new Map(opts.files);
  const warnings: string[] = [];
  const generated: string[] = [];
  if (open77Capable(m)) {
    const clash = OPEN77_GENERATED_FILES.filter((f) => files.has(f));
    if (clash.length > 0) {
      throw new EscrowFileSetError(
        "reserved_file",
        `${clash.join(", ")}: this name is generated for OPEN//77 in a protected release. Rename the file, or ship the resource in OPEN//77 format (open77.lua as its manifest).`,
      );
    }
    for (const [path, data] of open77ShimFiles(m, opts.shimDir)) {
      files.set(path, data);
      generated.push(path);
    }
    files.set("open77.lua", Buffer.from(open77Manifest(m, warnings, opts.manifestFile), "utf8"));
    generated.push("open77.lua");
  }
  const clientFacing = clientFacingFiles(m, [...opts.files.keys()]);
  const allowlist = [...new Set([...clientFacing, ...generated.sort(), ...opts.allowlist])];
  return { files, allowlist, generated, warnings };
}
