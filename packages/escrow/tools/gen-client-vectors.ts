// Generates the client-escrow vectors: a scriptgo-client-escrow/1 container of stripped Lua 5.4.8
// bytecode, its keys and wraps, from fixed test material, so the C loader and the .NET kit can check
// they read the same bytes. Deterministic: running this twice writes the same files, and
// packages/escrow/test/client-escrow.test.ts rebuilds every value.
//
// Run: node packages/escrow/tools/gen-client-vectors.ts   (Node 22.18+ runs TypeScript directly)
// Output (test-only material, never a real key):
//   packages/escrow/test/vectors/client-vectors.json
//   sdk/native/tests/client_vector.h            (the native CTest suite, the same values)
// The .NET tests embed the JSON where it is written (ScriptGo.Host.Tests.csproj).
import { createHash } from "node:crypto";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { clientVectors } from "../test/vectors/client-build.ts";

const here = dirname(fileURLToPath(import.meta.url));
const repo = join(here, "..", "..", "..");
const out = join(here, "..", "test", "vectors", "client-vectors.json");
const headerOut = join(repo, "sdk", "native", "tests", "client_vector.h");
const v = clientVectors();
const json = JSON.stringify(v, null, 2) + "\n";
for (const file of [out]) {
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, json);
  console.log(`wrote ${file}`);
}

type Wrap = { epk: string; nonce: string; wrapped: string };
const c = v as {
  keyId: string; signerPublicKey: string; containerBase64: string; legacyContainerBase64: string; strangerContainerBase64: string; foreignTargetBase64: string; lyingBase64: string; permutedBase64: string;
  target: { luacHeader: string };
  chunks: { path: string; bytes: number; sha256: string; lines: number[] }[];
  server: { privateKey: string; aad: string; wrapped: Wrap };
  session: { privateKey: string; aad: string; wrapped: Wrap; otherWrapped: Wrap; assetKeyWrapped: Wrap };
};
const b64u = (s: string) => Buffer.from(s, "base64url");
const lines: string[] = [];
const bytes = (name: string, data: Buffer) => {
  const rows: string[] = [];
  for (let i = 0; i < data.length; i += 16) rows.push("    " + [...data.subarray(i, i + 16)].map((x) => `0x${x.toString(16).padStart(2, "0")}`).join(", ") + ",");
  lines.push(`static const unsigned char ${name}[] = {`, ...(rows.length ? rows : ["    0x00,"]), "};", `static const size_t ${name}_len = ${data.length};`, "");
};
const str = (name: string, s: string) => lines.push(`static const char ${name}[] = ${JSON.stringify(s)};`, "");
const wrap = (name: string, w: Wrap) => {
  bytes(`${name}_EPK`, b64u(w.epk));
  bytes(`${name}_NONCE`, b64u(w.nonce));
  bytes(`${name}_WRAPPED`, b64u(w.wrapped));
};

lines.push(
  "/* GENERATED by packages/escrow/tools/gen-client-vectors.ts: do not edit. Test-only material, never a real key.",
  " * The same vector as packages/escrow/test/vectors/client-vectors.json. */",
  "#ifndef SCRIPTGO_CLIENT_VECTOR_H",
  "#define SCRIPTGO_CLIENT_VECTOR_H",
  "#include <stddef.h>",
  "",
);
bytes("CVEC_CONTAINER", Buffer.from(c.containerBase64, "base64"));
bytes("CVEC_LEGACY_CONTAINER", Buffer.from(c.legacyContainerBase64, "base64"));
bytes("CVEC_STRANGER_CONTAINER", Buffer.from(c.strangerContainerBase64, "base64"));
bytes("CVEC_FOREIGN_TARGET", Buffer.from(c.foreignTargetBase64, "base64"));
bytes("CVEC_LYING", Buffer.from(c.lyingBase64, "base64"));
bytes("CVEC_PERMUTED", Buffer.from(c.permutedBase64, "base64"));
bytes("CVEC_LUAC_HEADER", Buffer.from(c.target.luacHeader, "hex"));
str("CVEC_KEY_ID", c.keyId);
bytes("CVEC_SIGNER", b64u(c.signerPublicKey));
bytes("CVEC_SERVER_PRIVATE", b64u(c.server.privateKey));
str("CVEC_SERVER_AAD", c.server.aad);
wrap("CVEC_SERVER", c.server.wrapped);
bytes("CVEC_SESSION_PRIVATE", b64u(c.session.privateKey));
str("CVEC_SESSION_AAD", c.session.aad);
wrap("CVEC_SESSION", c.session.wrapped);
wrap("CVEC_OTHER", c.session.otherWrapped);
wrap("CVEC_ASSETKEY", c.session.assetKeyWrapped);
lines.push(`#define CVEC_CHUNK_COUNT ${c.chunks.length}`);
lines.push(`static const char* const CVEC_CHUNK_PATHS[] = { ${c.chunks.map((x) => JSON.stringify(x.path)).join(", ")} };`);
lines.push(`static const size_t CVEC_CHUNK_BYTES[] = { ${c.chunks.map((x) => `${x.bytes}u`).join(", ")} };`, "");
lines.push(`/* sha256 of the JSON vector: ${createHash("sha256").update(JSON.stringify(v)).digest("hex")} */`);
lines.push("#endif /* SCRIPTGO_CLIENT_VECTOR_H */", "");
writeFileSync(headerOut, lines.join("\n"));
console.log(`wrote ${headerOut}`);
