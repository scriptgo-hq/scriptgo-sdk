// Generates the asset vectors: a per-buyer fingerprinted build and an asset-escrow container, from
// fixed test material, so any other implementation (the platform, a platform's client hook in C++
// or C#) can check it produces and reads the same bytes. Everything is deterministic: running this
// twice writes the same files, and packages/escrow/test/assets.test.ts rebuilds every value.
//
// Run: node packages/escrow/tools/gen-asset-vectors.ts   (Node 22.18+ runs TypeScript directly)
// Output (test-only material, never a real key):
//   packages/escrow/test/vectors/asset-vectors.json
//   sdk/native/tests/asset_vector.h            (the native CTest suite, the same values)
import { createHash } from "node:crypto";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { unzipSync } from "fflate";
import { escrowedPreloadContainer } from "../src/index.ts";
import { assetVectors } from "../test/vectors/build.ts";

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "..", "test", "vectors", "asset-vectors.json");
const headerOut = join(here, "..", "..", "..", "sdk", "native", "tests", "asset_vector.h");
mkdirSync(dirname(out), { recursive: true });
const v = assetVectors();
writeFileSync(out, JSON.stringify(v, null, 2) + "\n");
console.log(`wrote ${out}`);

// ------------------------------------------------------------------------------- the C header
type Wrap = { epk: string; nonce: string; wrapped: string };
const a = v.assetEscrow as {
  contentKey: string; keyId: string; signerPublicKey: string; containerBase64: string; strangerContainerBase64: string;
  files: { path: string; bytes: number; sha256: string }[];
  server: { privateKey: string; publicKey: string; aad: string; wrapped: Wrap };
  client: { privateKey: string; publicKey: string; aad: string; wrapped: Wrap; otherWrapped: Wrap };
  escrowedCopy: { zipBase64: string; signerPublicKey: string; preloadEntry: string; preloadFiles: { path: string; sha256: string }[] };
};
const b64u = (s: string) => Buffer.from(s, "base64url");
const preload = Buffer.from(unzipSync(Buffer.from(a.escrowedCopy.zipBase64, "base64"))["night_market/dist/night_market.zip"]!);
const escrowed = escrowedPreloadContainer(preload)!;

const lines: string[] = [];
const bytes = (name: string, data: Buffer) => {
  const rows: string[] = [];
  for (let i = 0; i < data.length; i += 16) rows.push("    " + [...data.subarray(i, i + 16)].map((x) => `0x${x.toString(16).padStart(2, "0")}`).join(", ") + ",");
  lines.push(`static const unsigned char ${name}[] = {`, ...(rows.length ? rows : ["    0x00,"]), "};", `static const size_t ${name}_len = ${data.length};`, "");
};
const str = (name: string, s: string) => {
  lines.push(`static const char ${name}[] = ${JSON.stringify(s)};`, "");
};
const hex = (s: string) => Buffer.from(s, "hex");

lines.push(
  "/* GENERATED by packages/escrow/tools/gen-asset-vectors.ts: do not edit. Test-only material, never a real key.",
  " * The same vector as packages/escrow/test/vectors/asset-vectors.json (assetEscrow). */",
  "#ifndef SCRIPTGO_ASSET_VECTOR_H",
  "#define SCRIPTGO_ASSET_VECTOR_H",
  "#include <stddef.h>",
  "",
);
bytes("AVEC_CONTAINER", Buffer.from(a.containerBase64, "base64"));
bytes("AVEC_STRANGER_CONTAINER", Buffer.from(a.strangerContainerBase64, "base64"));
bytes("AVEC_CONTENT_KEY", Buffer.from(a.contentKey, "base64"));
str("AVEC_KEY_ID", a.keyId);
bytes("AVEC_SIGNER", b64u(a.signerPublicKey));
bytes("AVEC_SERVER_PRIVATE", b64u(a.server.privateKey));
bytes("AVEC_SERVER_EPK", b64u(a.server.wrapped.epk));
bytes("AVEC_SERVER_NONCE", b64u(a.server.wrapped.nonce));
bytes("AVEC_SERVER_WRAPPED", b64u(a.server.wrapped.wrapped));
str("AVEC_SERVER_AAD", a.server.aad);
bytes("AVEC_CLIENT_PRIVATE", b64u(a.client.privateKey));
bytes("AVEC_CLIENT_EPK", b64u(a.client.wrapped.epk));
bytes("AVEC_CLIENT_NONCE", b64u(a.client.wrapped.nonce));
bytes("AVEC_CLIENT_WRAPPED", b64u(a.client.wrapped.wrapped));
str("AVEC_CLIENT_AAD", a.client.aad);
bytes("AVEC_OTHER_EPK", b64u(a.client.otherWrapped.epk));
bytes("AVEC_OTHER_NONCE", b64u(a.client.otherWrapped.nonce));
bytes("AVEC_OTHER_WRAPPED", b64u(a.client.otherWrapped.wrapped));
lines.push(`#define AVEC_FILE_COUNT ${a.files.length}`);
lines.push(`static const char* const AVEC_FILE_PATHS[] = { ${a.files.map((f) => JSON.stringify(f.path)).join(", ")} };`);
lines.push(`static const unsigned long long AVEC_FILE_BYTES[] = { ${a.files.map((f) => `${f.bytes}ull`).join(", ")} };`);
a.files.forEach((f, i) => bytes(`AVEC_FILE_SHA256_${i}`, hex(f.sha256)));
lines.push(`static const unsigned char* const AVEC_FILE_SHA256[] = { ${a.files.map((_, i) => `AVEC_FILE_SHA256_${i}`).join(", ")} };`, "");
lines.push("/* The OPEN//77 escrowed preload of the copy for dep_7: its container and the preload's files. */");
bytes("AVEC_PRELOAD_CONTAINER", escrowed.container);
bytes("AVEC_PRELOAD_SIGNER", b64u(a.escrowedCopy.signerPublicKey));
lines.push(`#define AVEC_PRELOAD_FILE_COUNT ${a.escrowedCopy.preloadFiles.length}`);
lines.push(`static const char* const AVEC_PRELOAD_PATHS[] = { ${a.escrowedCopy.preloadFiles.map((f) => JSON.stringify(f.path)).join(", ")} };`);
a.escrowedCopy.preloadFiles.forEach((f, i) => bytes(`AVEC_PRELOAD_SHA256_${i}`, hex(f.sha256)));
lines.push(`static const unsigned char* const AVEC_PRELOAD_SHA256[] = { ${a.escrowedCopy.preloadFiles.map((_, i) => `AVEC_PRELOAD_SHA256_${i}`).join(", ")} };`, "");
lines.push(`/* sha256 of the whole header file input, for a quick identity check: ${createHash("sha256").update(JSON.stringify(v)).digest("hex")} */`);
lines.push("#endif /* SCRIPTGO_ASSET_VECTOR_H */", "");
writeFileSync(headerOut, lines.join("\n"));
console.log(`wrote ${headerOut}`);
