// The runnable README example of a package: a fenced block whose info string is `lua runnable`.
//
// `scriptgo verify` turns it into a throwaway resource `<package>_readme` that depends on the
// package and runs the block as its server script, next to the package, in every environment. Its
// output is part of the run's log, so the code a README shows is code that ran in that runtime,
// and a README example that breaks fails the run (`readme_example`, `no_runtime_errors`).
import { mkdirSync, mkdtempSync, readFileSync, existsSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import type { ParsedManifest } from "@scriptgo/manifest";

/** The first fenced block marked `lua runnable` (``` or ~~~), without its fences; null when none. */
export function runnableBlock(markdown: string): string | null {
  const text = markdown.replace(/\r\n/g, "\n");
  const re = /^(`{3,}|~{3,})[ \t]*lua\b([^\n]*)\n([\s\S]*?)^\1[ \t]*$/gm;
  for (const m of text.matchAll(re)) {
    if (/(^|\s)runnable(\s|$)/.test(m[2]!)) return m[3]!.replace(/\n+$/, "") + "\n";
  }
  return null;
}

/** `<package>_readme`, within the 64-character resource-name limit. */
export function exampleName(pkg: string): string {
  return `${pkg.slice(0, 64 - "_readme".length)}_readme`;
}

// Capabilities the example needs, read from what it calls. Only what is visibly used: a hidden
// requirement would make the example fail to start for a reason the README does not show.
const CAPABILITY_HINTS: [RegExp, string][] = [
  [/\bRegisterCommand\b/, "commands"],
  [/\bplayerJoining\b|\bplayerDropped\b|\bScriptGo\.players\b|\bGetPlayers\b/, "players"],
  [/\bScriptGo\.storage\b/, "storage"],
  [/\bScriptGo\.ui\b/, "ui"],
  [/\bScriptGo\.config\b|\bGetConvar\b/, "config"],
  [/\bScriptGo\.permissions\b/, "permissions"],
  [/\bScriptGo\.http\b/, "http"],
  [/\bScriptGo\.licensing\b/, "licensing"],
  [/\bScriptGo\.perks\b/, "perks"],
  [/\bScriptGo\.presence\b/, "presence"],
];

export function exampleCapabilities(code: string): string[] {
  const caps = ["events", "logging"];
  for (const [re, cap] of CAPABILITY_HINTS) if (re.test(code) && !caps.includes(cap)) caps.push(cap);
  return caps;
}

const quote = (s: string): string => JSON.stringify(s);
const list = (xs: string[]): string => `{ ${xs.map(quote).join(", ")} }`;

/** The generated manifest: same version and environments as the package, depends on it. */
export function exampleManifest(m: ParsedManifest, code: string): string {
  const lines = [
    `-- Generated by scriptgo verify from the runnable Lua block of ${m.name}/README.md.`,
    `resource ${quote(exampleName(m.name))}`,
    `version ${quote(m.version)}`,
    `description ${quote(`README example of ${m.name}`)}`,
    `scriptgo_version ">=0.1.0"`,
  ];
  if (m.environments.length > 0) lines.push(`environments ${list(m.environments)}`);
  lines.push(`capabilities ${list(exampleCapabilities(code))}`);
  lines.push(`dependency ${quote(m.name)}`);
  lines.push(`server_script "server/main.lua"`);
  return lines.join("\n") + "\n";
}

export interface ReadmeExample {
  name: string;
  /** The generated resource folder (its name is the resource name). */
  dir: string;
  code: string;
  cleanup(): void;
}

/**
 * Writes the example resource of the package at `pkgDir` into a new temporary folder (or under
 * `parent`). Null when the package has no README or its README has no runnable block.
 */
export function writeReadmeExample(pkgDir: string, m: ParsedManifest, parent?: string): ReadmeExample | null {
  const readme = join(pkgDir, "README.md");
  if (!existsSync(readme)) return null;
  const code = runnableBlock(readFileSync(readme, "utf8"));
  if (!code) return null;
  const base = parent ?? mkdtempSync(join(tmpdir(), "scriptgo-readme-"));
  const name = exampleName(m.name);
  const dir = join(base, name);
  mkdirSync(join(dir, "server"), { recursive: true });
  writeFileSync(join(dir, "scriptgo.lua"), exampleManifest(m, code));
  writeFileSync(join(dir, "server", "main.lua"), code);
  return {
    name, dir, code,
    cleanup: () => rmSync(parent ? dir : base, { recursive: true, force: true }),
  };
}
