// `scriptgo verify --env fivem`: the resource and its dependencies, packed for FiveM, on a real
// FXServer, and its console read back into a CompatibilityRun.
//
//   - FXServer refuses to start without `sv_licenseKey`, a registration key from the Cfx.re portal
//     (measured on build 38435: "Fatal Error: This server does not have a license key
//     specified", before any resource starts; `sv_lan 1` does not change it). Getting a key needs
//     a Cfx.re account and acceptance of the Rockstar Games Creator Platform License Agreement:
//     the owner's decision. The key is read from SCRIPTGO_FIVEM_LICENSE_KEY and passed as
//     `+set sv_licenseKey <key>`; without it the run is `skipped`, never `verified`.
//   - The server binds 127.0.0.1:<port> only (TCP and UDP, default 30121), is kept off the public
//     server list (`sv_master1 ""` makes the heartbeat private), and `loopback_only` checks its
//     listening sockets on Windows.
//   - Only the server half runs: no game client is started.
//   - The console lines it reads were taken from the FXServer binaries of build 38435:
//     "Started resource %s", "Couldn't start resource %s.", "^1SCRIPT ERROR: %s^7" on channel
//     `script:<resource>`, "Error loading script %s in resource %s: %s", "Failed to load script %s.",
//     "Server license key authentication succeeded. Welcome!", "Could not authenticate server
//     license key.", and the version string "FXServer-master SERVER v1.0.0.<build> win32".
import { spawn, spawnSync, type ChildProcess } from "node:child_process";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { basename, dirname, join, resolve } from "node:path";
import type { ParsedManifest } from "@scriptgo/manifest";
import { apiChecks, closure, selfChecks, type Check, type Report } from "../commands/verify.ts";
import { fivemShimVersion, packForFivem } from "./fivem-pack.ts";
import type { ReadmeExample } from "./readme-example.ts";
import { readResource, repoRoot, type LoadedResource } from "./sdk.ts";
import type { StubRequest } from "./stub-api.ts";

export const FIVEM_PORT = 30121;
export const FIVEM_KEY_ENV = "SCRIPTGO_FIVEM_LICENSE_KEY";
export const FIVEM_SERVER_ENV = "SCRIPTGO_FIVEM_SERVER";

export interface FivemVerifyOptions {
  /** FXServer.exe (or run.sh); else SCRIPTGO_FIVEM_SERVER, else tools/runtimes/fivem/FXServer.exe. */
  server?: string;
  /** The Cfx.re registration key; the CLI reads it from SCRIPTGO_FIVEM_LICENSE_KEY only. */
  licenseKey?: string;
  port: number;
  settleMs: number;
  timeoutMs: number;
  /** Where the throwaway server-data folder goes; default: next to the server folder. */
  workDir?: string;
  stub?: { url: string; licenseKey: string; requests: StubRequest[]; label: string };
  example?: ReadmeExample | null;
  /** Tests only: a command run instead of the server binary (a fake FXServer, never a report). */
  launcher?: string[];
}

/** The options `scriptgo verify` passes, from its flags and the environment. */
export function fivemOptions(flags: Record<string, string>, stub?: FivemVerifyOptions["stub"], example?: ReadmeExample | null): FivemVerifyOptions {
  return {
    server: flags["fivem-server"],
    licenseKey: process.env[FIVEM_KEY_ENV],
    port: Number(flags["fivem-port"] ?? FIVEM_PORT),
    settleMs: Number(flags.settle ?? 2000),
    timeoutMs: Number(flags["fivem-timeout"] ?? 120000),
    workDir: flags["fivem-workdir"],
    stub,
    example,
  };
}

export function findFxServer(flag?: string): string | null {
  const p = flag ?? process.env[FIVEM_SERVER_ENV] ?? join(repoRoot, "tools", "runtimes", "fivem", "FXServer.exe");
  return p && existsSync(p) ? resolve(p) : null;
}

/** The artifact build, read from the version string inside the binary ("... SERVER v1.0.0.38435 win32"). */
export function fxServerBuild(server: string): string {
  const candidates = [server, join(dirname(server), "citizen-server-impl.dll"), join(dirname(server), "alpine", "opt", "cfx-server", "FXServer")];
  for (const file of candidates) {
    if (!existsSync(file)) continue;
    const m = /SERVER v1\.0\.0\.(\d+)/.exec(readFileSync(file).toString("latin1"));
    if (m) return m[1]!;
  }
  return "";
}

const cfgQuote = (s: string): string => `"${s.replace(/["\r\n]/g, "")}"`;

/** server.cfg for one verify run: loopback only, unlisted, one slot, the packed resources ensured in order. */
export function fivemServerCfg(port: number, names: string[], convars: Record<string, string> = {}): string {
  const lines = [
    "# Generated by `scriptgo verify --env fivem`. Loopback only, not listed, deleted after the run.",
    `endpoint_add_tcp "127.0.0.1:${port}"`,
    `endpoint_add_udp "127.0.0.1:${port}"`,
    "sv_maxclients 1",
    'sv_hostname "SCRIPT//GO verify"',
    "sv_endpointprivacy true",
    // An empty first master makes the heartbeat private: the server stays off the public list.
    'sv_master1 ""',
  ];
  for (const [k, v] of Object.entries(convars)) lines.push(`set ${k} ${cfgQuote(v)}`);
  for (const n of names) lines.push(`ensure ${n}`);
  return lines.join("\n") + "\n";
}

export interface FxConsole {
  lines: string[];
  started: Set<string>;
  /** Resource -> first error line (a failed start, a script error or a script that did not load). */
  failed: Map<string, string>;
  errorLines: string[];
  licenseOk: boolean;
  licenseError: string | null;
  fatal: string | null;
}

export function newFxConsole(): FxConsole {
  return { lines: [], started: new Set(), failed: new Map(), errorLines: [], licenseOk: false, licenseError: null, fatal: null };
}

/** Removes ANSI escapes and FiveM colour codes (^0-^9). */
export function plainLine(raw: string): string {
  // eslint-disable-next-line no-control-regex
  return raw.replace(/\x1b\[[0-9;]*m/g, "").replace(/\^[0-9]/g, "").trimEnd();
}

/** Reads one console line into the state; `ours` are the resources this run packed. */
export function readFxLine(state: FxConsole, raw: string, ours: string[]): void {
  const line = plainLine(raw);
  if (!line.trim()) return;
  state.lines.push(line);
  const mark = (name: string, why: string): void => {
    if (!ours.includes(name)) return;
    state.errorLines.push(line);
    if (!state.failed.has(name)) state.failed.set(name, why);
  };
  let m: RegExpExecArray | null;
  if ((m = /Started resource ([A-Za-z0-9_-]+)/.exec(line))) state.started.add(m[1]!);
  else if ((m = /Couldn't start resource ([A-Za-z0-9_-]+)/.exec(line))) mark(m[1]!, line.trim());
  else if ((m = /\[\s*script:([A-Za-z0-9_-]+)\]\s*SCRIPT ERROR: (.*)$/.exec(line))) mark(m[1]!, m[2]!);
  else if ((m = /Error loading script (\S+) in resource ([A-Za-z0-9_-]+): (.*)$/.exec(line))) mark(m[2]!, `${m[1]}: ${m[3]}`);
  else if ((m = /Failed to load script @?([A-Za-z0-9_-]+)\/(\S+?)\.?$/.exec(line))) mark(m[1]!, line.trim());
  if (/Server license key authentication succeeded/.test(line)) state.licenseOk = true;
  if (/Could not authenticate server license key|does not have a license key specified|error occurred while checking server license key/.test(line)) {
    state.licenseError ??= line.replace(/^\[[^\]]*\]\s*/, "");
  }
  if ((m = /^Fatal Error: (.*)$/.exec(line))) state.fatal ??= m[1]!;
}

/** Listening sockets of a process (Windows): TCP listeners and the UDP endpoint on the game port. */
function listeningAddresses(pid: number, port: number): string[] | null {
  if (process.platform !== "win32") return null;
  const script = [
    `$t = Get-NetTCPConnection -OwningProcess ${pid} -State Listen -ErrorAction SilentlyContinue | ForEach-Object { "tcp $($_.LocalAddress):$($_.LocalPort)" }`,
    `$u = Get-NetUDPEndpoint -OwningProcess ${pid} -LocalPort ${port} -ErrorAction SilentlyContinue | ForEach-Object { "udp $($_.LocalAddress):$($_.LocalPort)" }`,
    "@($t) + @($u) | Where-Object { $_ } | ForEach-Object { $_ }",
  ].join("; ");
  const r = spawnSync("powershell", ["-NoProfile", "-Command", script], { encoding: "utf8" });
  if (r.status !== 0) return null;
  return (r.stdout ?? "").split(/\r?\n/).map((s) => s.trim()).filter(Boolean);
}

const LOOPBACK = /^(tcp|udp) (127\.\d+\.\d+\.\d+|::1):\d+$/;

/** Stops the server: `quit` on its console, then the whole process tree, then anything of ours still on the port. */
async function stopServer(child: ChildProcess, exited: Promise<unknown>, server: string, port: number): Promise<void> {
  try {
    child.stdin?.write("quit \"scriptgo verify finished\"\n");
  } catch {
    // stdin already closed
  }
  const gone = await Promise.race([exited.then(() => true), new Promise<boolean>((r) => setTimeout(() => r(false), 8000))]);
  if (!gone && child.pid) {
    if (process.platform === "win32") spawnSync("taskkill", ["/PID", String(child.pid), "/T", "/F"], { encoding: "utf8" });
    else child.kill("SIGKILL");
    await Promise.race([exited, new Promise((r) => setTimeout(r, 5000))]);
  }
  if (process.platform === "win32") {
    // Whatever still holds our port and runs this same server binary (a stray child process).
    const script = [
      `$ids = @(Get-NetTCPConnection -LocalPort ${port} -ErrorAction SilentlyContinue | ForEach-Object OwningProcess) + @(Get-NetUDPEndpoint -LocalPort ${port} -ErrorAction SilentlyContinue | ForEach-Object OwningProcess)`,
      `$ids | Sort-Object -Unique | ForEach-Object { $p = Get-Process -Id $_ -ErrorAction SilentlyContinue; if ($p -and $p.Path -eq '${server.replace(/'/g, "''")}') { Stop-Process -Id $_ -Force } }`,
    ].join("; ");
    spawnSync("powershell", ["-NoProfile", "-Command", script], { encoding: "utf8" });
  }
}

export async function verifyFivem(res: LoadedResource, m: ParsedManifest, search: string[], opts: FivemVerifyOptions): Promise<Report> {
  const started = Date.now();
  const checks: Check[] = [];
  let runtimeVersion = "";
  // Packing alone proves nothing about the runtime: without a server run the report is skipped.
  const status = (): Report["status"] => {
    if (checks.some((c) => c.status === "failed")) return "failing";
    return checks.some((c) => c.name === "server_run" && c.status === "passed") ? "verified" : "skipped";
  };
  const report = (log: string, evidence: Record<string, unknown> = {}): Report => ({
    package: m.name, version: m.version, environment: "fivem", status: status(), runtimeVersion,
    adapterVersion: fivemShimVersion(), luaVersion: "Lua 5.4", durationMs: Date.now() - started, checks, log, evidence,
  });
  checks.push({
    name: "environment_declared", status: m.environments.length === 0 || m.environments.includes("fivem") ? "passed" : "failed",
    message: m.environments.join(", "),
  });
  const { order, missing } = closure(res, search);
  checks.push({ name: "dependencies_resolved", status: missing.length === 0 ? "passed" : "failed", message: missing.join(", ") });
  if (missing.length > 0) return report("");
  if (opts.example) order.push(readResource(opts.example.dir));

  const server = opts.launcher ? opts.launcher[opts.launcher.length - 1]! : findFxServer(opts.server);
  const base = opts.workDir ?? (server && !opts.launcher ? join(dirname(dirname(server)), "scriptgo-verify") : tmpdir());
  mkdirSync(base, { recursive: true });
  const run = mkdtempSync(join(base, "run-"));
  const names: string[] = [];
  let packed = true;
  for (const r of order) {
    const p = packForFivem(r, join(run, "resources"));
    const name = r.result.ok ? r.result.manifest.name : r.root;
    names.push(name);
    if (p.errors.length > 0) {
      packed = false;
      checks.push({ name: `packs:${name}`, status: "failed", message: p.errors.map((e) => `${e.code}: ${e.message}`).join("; ") });
    } else {
      checks.push({ name: `packs:${name}`, status: "passed", message: p.warnings.join("; ") });
    }
  }
  const key = opts.licenseKey?.trim() ?? "";
  const skip = !packed ? null
    : !server ? `no FXServer: pass --fivem-server <FXServer.exe> or set ${FIVEM_SERVER_ENV}`
    : !key ? `no sv_licenseKey: FXServer will not start without a Cfx.re registration key (build 38435: fatal error before any resource starts). The owner sets ${FIVEM_KEY_ENV}`
    : null;
  if (!packed || skip) {
    if (skip) checks.push({ name: "server_run", status: "skipped", message: skip });
    rmSync(run, { recursive: true, force: true });
    return report("");
  }
  const serverPath = server!;
  runtimeVersion = opts.launcher ? "fake FXServer (test)" : `FXServer ${fxServerBuild(serverPath) || "(build unknown)"}`;

  const stub = opts.stub;
  const firstRequest = stub?.requests.length ?? 0;
  // ScriptGo.config reads the convar "<resource>:<key>".
  const convars: Record<string, string> = stub
    ? { scriptgo_api: stub.url, [`${m.name}:api`]: stub.url, [`${m.name}:license_key`]: stub.licenseKey }
    : {};
  writeFileSync(join(run, "server.cfg"), fivemServerCfg(opts.port, names, convars));

  const state = newFxConsole();
  const fxArgs = ["+set", "sv_licenseKey", key, "+exec", "server.cfg"];
  const [cmd, ...pre] = opts.launcher ?? [serverPath];
  const child = spawn(cmd!, [...pre, ...fxArgs], { cwd: run, stdio: ["pipe", "pipe", "pipe"], windowsHide: true });
  const onData = (chunk: Buffer): void => {
    for (const raw of chunk.toString("utf8").split(/\r?\n/)) readFxLine(state, raw.split(run).join("<run>"), names);
  };
  child.stdout!.on("data", onData);
  child.stderr!.on("data", onData);
  let exitCode: number | null | undefined;
  const exited = new Promise<void>((done) => {
    child.on("exit", (code) => { exitCode = code; done(); });
    child.on("error", (e) => { state.fatal ??= String(e); exitCode = null; done(); });
  });

  const deadline = Date.now() + opts.timeoutMs;
  const settledAll = (): boolean => names.every((n) => state.started.has(n) || state.failed.has(n));
  const selfDone = (): boolean => !state.lines.some((l) => /SGCHECK (PASS|FAIL)/.test(l)) || state.lines.some((l) => /SGCHECK DONE/.test(l));
  const wait = (ms: number): Promise<void> => new Promise((r) => setTimeout(r, ms));
  // The key is authenticated asynchronously: wait for both the authentication and every resource.
  const ready = (): boolean => state.licenseOk && settledAll();
  while (Date.now() < deadline && exitCode === undefined && !state.fatal && !state.licenseError && !ready()) await wait(100);
  // Let timers and threads run: errors raised after start count too, and self-checks finish.
  if (exitCode === undefined && ready()) {
    await wait(opts.settleMs);
    while (Date.now() < deadline && exitCode === undefined && !selfDone()) await wait(100);
  }
  const sockets = exitCode === undefined && child.pid && !opts.launcher ? listeningAddresses(child.pid, opts.port) : null;
  if (exitCode === undefined) await stopServer(child, exited, serverPath, opts.port);
  else await exited;

  const ranResources = state.licenseOk && settledAll() && !state.fatal && !state.licenseError;
  checks.push({
    name: "license_key",
    status: state.licenseOk && !state.licenseError && !state.fatal ? "passed" : "failed",
    message: state.licenseError ?? state.fatal ?? (state.licenseOk ? "authenticated" : "no authentication line seen"),
  });
  checks.push({
    name: "server_run", status: ranResources ? "passed" : "failed",
    message: ranResources ? `${names.length} resources reached a verdict` : state.fatal ?? state.licenseError ?? `server exited (${exitCode}) or timed out before every resource started`,
  });
  if (sockets) {
    const open = sockets.filter((s) => !LOOPBACK.test(s));
    checks.push({ name: "loopback_only", status: open.length === 0 ? "passed" : "failed", message: open.length === 0 ? sockets.join(", ") : `listening beyond loopback: ${open.join(", ")}` });
  } else {
    checks.push({ name: "loopback_only", status: "skipped", message: opts.launcher ? "fake server" : "socket listing needs Windows PowerShell" });
  }
  for (const n of names) {
    if (opts.example && n === opts.example.name) continue;
    checks.push({ name: `starts:${n}`, status: state.started.has(n) && !state.failed.has(n) ? "passed" : "failed", message: state.failed.get(n) ?? "" });
  }
  if (opts.example) {
    const n = opts.example.name;
    const ok = state.started.has(n) && !state.failed.has(n);
    checks.push({ name: "readme_example", status: ok ? "passed" : "failed", message: ok ? `${n} started` : state.failed.get(n) ?? "did not start" });
  }
  checks.push({ name: "no_runtime_errors", status: state.errorLines.length === 0 ? "passed" : "failed", message: state.errorLines[0] ?? "" });
  checks.push(...selfChecks(state.lines.join("\n")));
  if (stub) checks.push(...apiChecks(stub.requests, firstRequest, "fivem", fivemShimVersion()));
  rmSync(run, { recursive: true, force: true });

  const ourLine = (l: string): boolean =>
    names.some((n) => l.includes(`script:${n}]`) || l.includes(` ${n}`)) || /license key|Fatal Error|SCRIPT ERROR|Couldn't start/.test(l);
  // The licence key never reaches the stored report; nor do the server's folder and the stub's URL.
  let log = state.lines.filter(ourLine).join("\n").split(key).join("<sv_licenseKey>").split(dirname(serverPath)).join("<fxserver>");
  if (stub) log = log.split(stub.licenseKey).join("<license_key>").split(stub.url).join("<stub-api>");
  for (const c of checks) c.message = c.message.split(key).join("<sv_licenseKey>");
  return report(log, {
    serverBinary: basename(serverPath),
    build: runtimeVersion,
    resources: names,
    licenseKey: `from ${FIVEM_KEY_ENV}, not stored`,
    ...(stub ? { api: stub.label } : {}),
    ...(opts.example ? { readme_example: `${opts.example.name}: the runnable Lua block of README.md` } : {}),
  });
}
