// `scriptgo pack --target luanti|rust|hytale`: the asset delivery form of three environments whose
// script deployment is not a pack target (docs/spec/assets.md, "Delivery per environment").
//
//   luanti  <out>/mods/sgmedia_<name>/: a media mod. Luanti sends every file of a mod's textures/,
//           sounds/, models/, media/, locale/ and fonts/ folders to each client at join
//           (api.luanti.org/mods). When the package has scripts, <out>/mods/scriptgo/ is the
//           SCRIPT//GO mod with the resource in its resources/ folder.
//   rust    <out>/<map>.map: a custom map. The operator hosts it at an HTTP(S) URL and sets
//           server.levelurl; the server and every player download it from there. A plugin cannot
//           send files to players, so nothing else can be delivered on Rust.
//   hytale  <out>/mods/<pack>.zip: an asset pack for the server's mods/ folder; the server sends its
//           assets to players.
import { copyFileSync, existsSync, mkdirSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { expandGlob, type ParsedManifest } from "@scriptgo/manifest";
// @ts-expect-error plain ESM build script without type declarations
import { buildMod } from "../../../../sdk/adapters/luanti/build.mjs";
import { baseName, copyFiles, copyFingerprint, describePlan, flatNameClashes, hasScripts, planAssets, type AssetIssue, type AssetPlan } from "./assets.ts";
import { listFiles, type LoadedResource } from "./sdk.ts";

export interface AssetTargetPack {
  /** Folders or files written, for the summary line. */
  written: string[];
  warnings: string[];
  errors: AssetIssue[];
  assets?: AssetPlan;
  /** What the operator does next. */
  next: string[];
}

/** The media mod's name: Luanti mod names are [a-z0-9_]. */
export const luantiMediaModName = (resource: string): string => `sgmedia_${resource.toLowerCase().replace(/[^a-z0-9_]/g, "_")}`;

/** init.lua of the media mod: media mods need no code; this line only shows the mod loaded. */
export function luantiMediaInit(mod: string, count: number): string {
  return [
    `-- Generated by \`scriptgo pack --target luanti\`. The engine sends this mod's media to every`,
    "-- client at join; no code is needed for that. This line only records that the mod loaded.",
    `core.log("action", "[${mod}] ${count} media files")`,
    "",
  ].join("\n");
}

export function packForLuanti(res: LoadedResource, out: string): AssetTargetPack {
  const pack: AssetTargetPack = { written: [], warnings: [], errors: [], next: [] };
  if (!res.result.ok) return { ...pack, errors: res.result.errors };
  const m = res.result.manifest;
  const scripts = hasScripts(m);
  const assets = planAssets(res, "luanti", { withoutAssets: scripts });
  pack.assets = assets;
  pack.warnings.push(...assets.warnings);
  if (assets.errors.length > 0) return { ...pack, errors: assets.errors };
  if (assets.delivered.length > 0) {
    const mod = luantiMediaModName(m.name);
    const dest = join(out, "mods", mod);
    if (existsSync(dest)) rmSync(dest, { recursive: true });
    mkdirSync(dest, { recursive: true });
    copyFiles(res.root, dest, assets.delivered);
    copyFingerprint(assets, dest);
    writeFileSync(join(dest, "mod.conf"), `name = ${mod}\ndescription = ${(m.title ?? m.name).replace(/[\r\n]/g, " ")} (SCRIPT//GO media)\n`);
    writeFileSync(join(dest, "init.lua"), luantiMediaInit(mod, assets.delivered.length));
    pack.written.push(dest);
  }
  if (scripts) {
    const mod = buildMod(join(out, "mods", "scriptgo")) as string;
    copyFiles(res.root, join(mod, "resources", m.name), luantiResourceFiles(m, listFiles(res.root), res.manifestFile));
    pack.written.push(mod);
  }
  pack.next.push(`copy ${join(out, "mods")} into the server's mods/ folder (or the game's), and enable the mods in world.mt (load_mod_<name> = true)`);
  return pack;
}

/** The resource as the SCRIPT//GO mod loads it: the manifest and the files it references. */
function luantiResourceFiles(m: ParsedManifest, files: string[], manifestFile: string): string[] {
  const set = new Set<string>([manifestFile]);
  for (const p of [...m.sharedScripts, ...m.serverScripts, ...m.clientScripts, ...(m.environmentScripts["luanti"] ?? []), ...m.files]) {
    for (const f of expandGlob(p, files)) set.add(f);
  }
  return [...set].sort();
}

export function packForRust(res: LoadedResource, out: string): AssetTargetPack {
  const pack: AssetTargetPack = { written: [], warnings: [], errors: [], next: [] };
  if (!res.result.ok) return { ...pack, errors: res.result.errors };
  const m = res.result.manifest;
  const assets = planAssets(res, "rust");
  pack.assets = assets;
  pack.warnings.push(...assets.warnings);
  if (assets.errors.length > 0) return { ...pack, errors: assets.errors };
  mkdirSync(out, { recursive: true });
  for (const f of assets.native) {
    copyFileSync(join(res.root, ...f.split("/")), join(out, baseName(f)));
    pack.written.push(join(out, baseName(f)));
    pack.next.push(`host ${baseName(f)} at an HTTP(S) URL the server and players can reach, then start the server with +server.levelurl "<that URL>"`);
  }
  if (hasScripts(m)) pack.warnings.push("this target writes the map only: the package's scripts run through the SCRIPT//GO Rust bridge (sdk/adapters/rust)");
  pack.warnings.push("every player who joins downloads the map from that URL as is: the download from SCRIPT//GO is licence-gated, but a .map is a loose file, so copies are not fingerprinted per buyer");
  return pack;
}

export function packForHytale(res: LoadedResource, out: string): AssetTargetPack {
  const pack: AssetTargetPack = { written: [], warnings: [], errors: [], next: [] };
  if (!res.result.ok) return { ...pack, errors: res.result.errors };
  const m = res.result.manifest;
  const assets = planAssets(res, "hytale");
  pack.assets = assets;
  pack.warnings.push(...assets.warnings);
  if (assets.errors.length > 0) return { ...pack, errors: assets.errors };
  const clashes = flatNameClashes(assets.native, "Hytale's mods/");
  if (clashes.length > 0) return { ...pack, errors: clashes };
  const dest = join(out, "mods");
  mkdirSync(dest, { recursive: true });
  for (const f of assets.native) {
    copyFileSync(join(res.root, ...f.split("/")), join(dest, baseName(f)));
    pack.written.push(join(dest, baseName(f)));
  }
  pack.next.push(`copy ${dest} into the Hytale server's mods/ folder; the server sends the pack's assets to players`);
  if (hasScripts(m)) pack.warnings.push("this target writes the asset pack only: the package's scripts run through the SCRIPT//GO Hytale plugin (sdk/adapters/hytale)");
  pack.warnings.push("Hytale asset packs are validated by SCRIPT//GO but have not been loaded by a real Hytale server yet");
  return pack;
}

/** `scriptgo pack --target luanti|rust|hytale`: prints the result, returns the exit code. */
export function packAssetTargetCommand(res: LoadedResource, target: "luanti" | "rust" | "hytale", out: string): number {
  const r = target === "luanti" ? packForLuanti(res, out) : target === "rust" ? packForRust(res, out) : packForHytale(res, out);
  for (const w of r.warnings) console.log(`warning ${w}`);
  for (const e of r.errors) console.error(`error ${e.code}: ${e.message}`);
  if (r.errors.length > 0) return 1;
  if (r.assets) for (const line of describePlan(r.assets, target)) console.log(line);
  if (r.written.length === 0) {
    console.error(`error nothing_to_pack: ${target} delivers none of this package's files`);
    return 1;
  }
  for (const w of r.written) console.log(`packed for ${target} -> ${w}`);
  for (const n of r.next) console.log(`next: ${n}`);
  return 0;
}
